-- PixelValln SHOP: customer account, wallet, promo and account-linked orders
-- Run in Supabase SQL Editor after taking a backup. Does not contain service-role keys.

create table if not exists public.customer_profiles (
 user_id uuid primary key references auth.users(id) on delete cascade,
 username text not null default '', full_name text not null default '', whatsapp text not null default '', avatar_url text,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
alter table public.orders add column if not exists subtotal bigint;
alter table public.orders add column if not exists discount_amount bigint not null default 0;
alter table public.orders add column if not exists promo_code text;
alter table public.orders add column if not exists user_id uuid references auth.users(id) on delete set null;
alter table public.customer_profiles add column if not exists avatar_url text;

create table if not exists public.store_promos (
 id bigint generated by default as identity primary key,
 code text not null unique,
 discount_type text not null check (discount_type in ('percent','fixed')),
 discount_value bigint not null check (discount_value > 0),
 min_subtotal bigint not null default 0 check (min_subtotal >= 0),
 max_discount bigint,
 starts_at timestamptz not null default now(), ends_at timestamptz,
 max_uses integer, used_count integer not null default 0,
 is_active boolean not null default true,
 game_ids text[], product_keyword text,
 created_at timestamptz not null default now()
);
create table if not exists public.wallet_topups (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 topup_code text not null unique,
 amount bigint not null check (amount between 10000 and 5000000),
 payment_method text not null check (payment_method in ('QRIS','DANA','GoPay','OVO','ShopeePay','Transfer Bank')),
 status text not null default 'pending' check (status in ('pending','approved','rejected')),
 created_at timestamptz not null default now(), reviewed_at timestamptz, reviewed_by uuid references auth.users(id), admin_note text
);
create table if not exists public.wallet_ledger (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 topup_id bigint references public.wallet_topups(id), transaction_type text not null,
 description text not null default '', amount bigint not null,
 created_at timestamptz not null default now()
);
create index if not exists orders_user_created_idx on public.orders(user_id,created_at desc);
create index if not exists wallet_topups_user_created_idx on public.wallet_topups(user_id,created_at desc);
create index if not exists wallet_ledger_user_created_idx on public.wallet_ledger(user_id,created_at desc);

alter table public.customer_profiles enable row level security;
alter table public.wallet_topups enable row level security;
alter table public.wallet_ledger enable row level security;
alter table public.store_promos enable row level security;
revoke all on public.customer_profiles,public.wallet_topups,public.wallet_ledger,public.store_promos from anon,authenticated;

