create or replace function public.update_customer_profile(p_username text,p_full_name text,p_whatsapp text default '')
returns boolean language plpgsql security definer set search_path='' as $$
declare v_user uuid:=auth.uid();
begin
 if v_user is null then raise exception 'Silakan login terlebih dahulu'; end if;
 if length(trim(coalesce(p_username,''))) not between 3 and 30 or trim(p_username) !~ '^[A-Za-z0-9._]+$' then raise exception 'Username harus 3–30 karakter dan hanya berisi huruf, angka, titik, atau garis bawah'; end if;
 if length(trim(coalesce(p_full_name,''))) not between 2 and 80 then raise exception 'Nama lengkap harus 2–80 karakter'; end if;
 if length(regexp_replace(coalesce(p_whatsapp,''),'\D','','g')) > 20 then raise exception 'Nomor WhatsApp tidak valid'; end if;
 insert into public.customer_profiles(user_id,username,full_name,whatsapp,updated_at) values(v_user,trim(p_username),trim(p_full_name),trim(coalesce(p_whatsapp,'')),now())
 on conflict(user_id) do update set username=excluded.username,full_name=excluded.full_name,whatsapp=excluded.whatsapp,updated_at=now();
 return true;
end $$;
revoke all on function public.update_customer_profile(text,text,text) from public; grant execute on function public.update_customer_profile(text,text,text) to authenticated;

create or replace function public.update_customer_avatar(p_avatar_url text)
returns boolean language plpgsql security definer set search_path='' as $$
declare v_user uuid:=auth.uid();
begin
 if v_user is null then raise exception 'Silakan login terlebih dahulu'; end if;
 if p_avatar_url is not null and (length(p_avatar_url)>1000 or p_avatar_url not like 'https://%/storage/v1/object/public/profile-avatars/'||v_user::text||'/%') then
  raise exception 'URL foto profil tidak valid';
 end if;
 insert into public.customer_profiles(user_id,username,full_name,avatar_url,updated_at)
 values(v_user,split_part(coalesce((select email from auth.users where id=v_user),''),'@',1),split_part(coalesce((select email from auth.users where id=v_user),''),'@',1),p_avatar_url,now())
 on conflict(user_id) do update set avatar_url=excluded.avatar_url,updated_at=now();
 return true;
end $$;
revoke all on function public.update_customer_avatar(text) from public; grant execute on function public.update_customer_avatar(text) to authenticated;

create or replace function public.get_customer_account_dashboard()
returns jsonb language plpgsql security definer set search_path='' as $$
declare v_user uuid:=auth.uid(); v_result jsonb;
begin
 if v_user is null then raise exception 'Silakan login terlebih dahulu'; end if;
 insert into public.customer_profiles(user_id,username,full_name) select v_user,split_part(u.email,'@',1),split_part(u.email,'@',1) from auth.users u where u.id=v_user on conflict(user_id) do nothing;
 select jsonb_build_object(
  'profile',(select to_jsonb(p) from public.customer_profiles p where p.user_id=v_user),
  'balance',coalesce((select sum(l.amount) from public.wallet_ledger l where l.user_id=v_user),0),
  'orders',coalesce((select jsonb_agg(to_jsonb(o) order by o.created_at desc) from (select order_code,game_name,product_name,amount,payment_method,payment_status,order_status,created_at,discount_amount,promo_code from public.orders where user_id=v_user order by created_at desc limit 200) o),'[]'::jsonb),
  'topups',coalesce((select jsonb_agg(to_jsonb(t) order by t.created_at desc) from (select topup_code,amount,payment_method,status,created_at from public.wallet_topups where user_id=v_user order by created_at desc limit 100) t),'[]'::jsonb),
  'ledger',coalesce((select jsonb_agg(x order by x->>'created_at' desc) from (select jsonb_build_object('created_at',l.created_at,'description',l.description,'transaction_type',l.transaction_type,'amount',l.amount,'balance_after',(select coalesce(sum(l2.amount),0) from public.wallet_ledger l2 where l2.user_id=v_user and l2.created_at<=l.created_at)) x from public.wallet_ledger l where l.user_id=v_user order by l.created_at desc limit 100) q),'[]'::jsonb)
 ) into v_result;
 return v_result;
end $$;
revoke all on function public.get_customer_account_dashboard() from public; grant execute on function public.get_customer_account_dashboard() to authenticated;

create or replace function public.create_wallet_topup_request(p_amount bigint,p_payment_method text)
returns table(topup_code text,amount bigint,status text) language plpgsql security definer set search_path='' as $$
declare v_user uuid:=auth.uid(); v_code text;
begin
 if v_user is null then raise exception 'Silakan login terlebih dahulu'; end if;
 if p_amount not in (10000,20000,50000,100000,200000,500000) then raise exception 'Nominal isi saldo tidak tersedia'; end if;
 if p_payment_method not in ('QRIS','DANA','GoPay','OVO','ShopeePay','Transfer Bank') then raise exception 'Metode pembayaran tidak valid'; end if;
 v_code:='PVW-'||upper(substr(replace(gen_random_uuid()::text,'-',''),1,10));
 insert into public.wallet_topups(user_id,topup_code,amount,payment_method) values(v_user,v_code,p_amount,p_payment_method);
 return query select v_code,p_amount,'pending'::text;
end $$;
revoke all on function public.create_wallet_topup_request(bigint,text) from public; grant execute on function public.create_wallet_topup_request(bigint,text) to authenticated;

create or replace function public.validate_store_promo(p_code text,p_subtotal bigint,p_game_id text default '',p_product_name text default '')
returns jsonb language plpgsql security definer set search_path='' as $$
declare p public.store_promos%rowtype; v_discount bigint;
begin
 select * into p from public.store_promos where code=upper(trim(p_code)) and is_active=true and starts_at<=now() and (ends_at is null or ends_at>=now()) and (max_uses is null or used_count<max_uses) limit 1;
 if not found then return jsonb_build_object('valid',false,'message','Kode promo tidak ditemukan, tidak aktif, atau sudah kedaluwarsa'); end if;
 if p_subtotal<p.min_subtotal then return jsonb_build_object('valid',false,'message','Minimal belanja untuk promo ini adalah Rp'||p.min_subtotal); end if;
 if p.game_ids is not null and not (p_game_id=any(p.game_ids)) then return jsonb_build_object('valid',false,'message','Promo tidak berlaku untuk game ini'); end if;
 if p.product_keyword is not null and position(lower(p.product_keyword) in lower(coalesce(p_product_name,'')))=0 then return jsonb_build_object('valid',false,'message','Promo tidak berlaku untuk produk ini'); end if;
 v_discount:=case when p.discount_type='percent' then floor(p_subtotal*p.discount_value/100.0)::bigint else p.discount_value end;
 if p.max_discount is not null then v_discount:=least(v_discount,p.max_discount); end if;
 v_discount:=least(greatest(v_discount,0),greatest(p_subtotal,0));
 return jsonb_build_object('valid',true,'code',p.code,'discount_amount',v_discount,'subtotal',p_subtotal,'total',greatest(0,p_subtotal-v_discount),'message','Promo valid');
end $$;
revoke all on function public.validate_store_promo(text,bigint,text,text) from public; grant execute on function public.validate_store_promo(text,bigint,text,text) to authenticated;

create or replace function public.create_authenticated_store_order_with_promo(
 p_game_id text,p_category_name text,p_product_name text,p_game_user_id text,p_game_server_id text,p_customer_contact text,p_payment_method text,p_promo_code text default null
) returns table(order_code text,amount bigint,subtotal bigint,discount_amount bigint,promo_code text)
language plpgsql security definer set search_path='' as $$
declare v_user uuid:=auth.uid(); v_product public.store_products%rowtype; v_code text; v_discount bigint:=0; v_promo public.store_promos%rowtype; v_amount bigint; v_balance bigint;
begin
 if v_user is null then raise exception 'Login diperlukan untuk membuat pesanan akun'; end if;
 if length(trim(coalesce(p_game_user_id,''))) not between 1 and 120 then raise exception 'ID pemain atau catatan tidak valid'; end if;
 if length(regexp_replace(coalesce(p_customer_contact,''),'\D','','g')) not between 9 and 20 then raise exception 'Nomor kontak tidak valid'; end if;
 if p_payment_method not in ('QRIS','GoPay','DANA','OVO','Transfer Bank','ShopeePay','Lainnya','Saldo PixelValln') then raise exception 'Metode pembayaran tidak valid'; end if;
 select * into v_product from public.store_products where game_id=p_game_id and category_name=p_category_name and product_name=p_product_name and is_active=true;
 if not found then raise exception 'Produk tidak ditemukan atau tidak aktif'; end if;
 if nullif(trim(coalesce(p_promo_code,'')),'') is not null then
   select * into v_promo from public.store_promos where code=upper(trim(p_promo_code)) and is_active=true and starts_at<=now() and (ends_at is null or ends_at>=now()) and (max_uses is null or used_count<max_uses) for update;
   if not found then raise exception 'Kode promo tidak valid atau sudah kedaluwarsa'; end if;
   if v_product.price<v_promo.min_subtotal then raise exception 'Belanja belum memenuhi minimal promo'; end if;
   if v_promo.game_ids is not null and not (p_game_id=any(v_promo.game_ids)) then raise exception 'Promo tidak berlaku untuk game ini'; end if;
   if v_promo.product_keyword is not null and position(lower(v_promo.product_keyword) in lower(p_product_name))=0 then raise exception 'Promo tidak berlaku untuk produk ini'; end if;
   v_discount:=case when v_promo.discount_type='percent' then floor(v_product.price*v_promo.discount_value/100.0)::bigint else v_promo.discount_value end;
   if v_promo.max_discount is not null then v_discount:=least(v_discount,v_promo.max_discount); end if;
   v_discount:=least(greatest(v_discount,0),v_product.price);
 end if;
 v_amount:=greatest(0,v_product.price-v_discount);
 if p_payment_method='Saldo PixelValln' then
   -- Serialize wallet spends per account to prevent simultaneous purchases overspending the same balance.
   insert into public.customer_profiles(user_id,username,full_name) select v_user,split_part(coalesce(u.email,''),'@',1),split_part(coalesce(u.email,''),'@',1) from auth.users u where u.id=v_user on conflict(user_id) do nothing;
   perform 1 from public.customer_profiles where user_id=v_user for update;
   select coalesce(sum(wl.amount),0) into v_balance from public.wallet_ledger as wl where wl.user_id=v_user;
   if v_balance<v_amount then raise exception 'Saldo tidak cukup. Saldo kamu %; total pesanan %.',v_balance,v_amount; end if;
 end if;
 v_code:='PV-'||upper(substr(replace(gen_random_uuid()::text,'-',''),1,10));
 insert into public.orders(order_code,user_id,customer_name,customer_contact,game_id,game_name,product_name,game_user_id,game_server_id,amount,subtotal,discount_amount,promo_code,payment_method,payment_status,order_status)
 values(v_code,v_user,null,trim(p_customer_contact),p_game_id,v_product.game_name,v_product.category_name||' — '||v_product.product_name,trim(p_game_user_id),nullif(trim(coalesce(p_game_server_id,'')),''),v_amount,v_product.price,v_discount,nullif(upper(trim(coalesce(p_promo_code,''))),''),p_payment_method,case when p_payment_method='Saldo PixelValln' then 'verified' else 'pending' end,'pending');
 if p_payment_method='Saldo PixelValln' then
   insert into public.wallet_ledger(user_id,transaction_type,description,amount) values(v_user,'purchase','Pembayaran pesanan '||v_code,-v_amount);
 end if;
 if v_promo.id is not null then update public.store_promos set used_count=used_count+1 where id=v_promo.id; end if;
 return query select v_code,v_amount,v_product.price,v_discount,nullif(upper(trim(coalesce(p_promo_code,''))),'');
end $$;
revoke all on function public.create_authenticated_store_order_with_promo(text,text,text,text,text,text,text,text) from public; grant execute on function public.create_authenticated_store_order_with_promo(text,text,text,text,text,text,text,text) to authenticated;

-- Admin-only wallet approval helper: run from authenticated admin account in SQL only after verifying payment.
create or replace function public.admin_review_wallet_topup(p_topup_code text,p_approve boolean,p_admin_note text default '')
returns boolean language plpgsql security definer set search_path='' as $$
declare v_topup public.wallet_topups%rowtype;
begin
 if auth.uid() is null or not coalesce(public.is_store_admin(),false) then raise exception 'Akses admin diperlukan'; end if;
 select * into v_topup from public.wallet_topups where topup_code=upper(trim(p_topup_code)) for update;
 if not found then raise exception 'Kode isi saldo tidak ditemukan'; end if;
 if v_topup.status<>'pending' then raise exception 'Permintaan ini sudah ditinjau'; end if;
 update public.wallet_topups set status=case when p_approve then 'approved' else 'rejected' end,reviewed_at=now(),reviewed_by=auth.uid(),admin_note=left(coalesce(p_admin_note,''),500) where id=v_topup.id;
 if p_approve then insert into public.wallet_ledger(user_id,topup_id,transaction_type,description,amount) values(v_topup.user_id,v_topup.id,'topup','Isi saldo disetujui: '||v_topup.topup_code,v_topup.amount); end if;
 return true;
end $$;
revoke all on function public.admin_review_wallet_topup(text,boolean,text) from public; grant execute on function public.admin_review_wallet_topup(text,boolean,text) to authenticated;

create or replace function public.admin_list_wallet_topups()
returns table(id bigint,topup_code text,user_id uuid,customer_email text,amount bigint,payment_method text,status text,created_at timestamptz,admin_note text)
language plpgsql security definer set search_path='' as $$
begin
 if auth.uid() is null or not coalesce(public.is_store_admin(),false) then raise exception 'Akses admin diperlukan'; end if;
 return query select t.id,t.topup_code,t.user_id,u.email::text,t.amount,t.payment_method,t.status,t.created_at,t.admin_note
 from public.wallet_topups t left join auth.users u on u.id=t.user_id order by t.created_at desc limit 300;
end $$;
revoke all on function public.admin_list_wallet_topups() from public; grant execute on function public.admin_list_wallet_topups() to authenticated;

